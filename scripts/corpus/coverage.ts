/*
 * Corpus coverage page.
 *
 * Reads every results.json under --reports (one per corpus job: the CI run's downloaded
 * artifacts, or local report dirs) and writes a Markdown page listing which metadata types
 * round-tripped in which projects. Generated, never hand-edited, so it can't drift from what
 * the corpus actually checked.
 *
 * Usage:
 *   npm run corpus:coverage -- --reports <dir> [--out <file>] [--source <label>] [--corpus <path>]
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFlags, requireString } from '../audit/lib.js';
import type { CorpusRepo } from './lib.js';

const HERE = dirname(fileURLToPath(import.meta.url));

const HELP_TEXT = `Usage: npm run corpus:coverage -- --reports <dir> [options]

Options:
  --reports <dir>    Directory searched (recursively) for corpus results.json files
  --out <file>       Output Markdown (default: scripts/corpus/COVERAGE.md)
  --source <label>   Where the results came from, shown on the page (e.g. a CI run URL)
  --corpus <path>    Corpus JSON, for each project's URL and pinned commit
                     (default: scripts/corpus/corpus.json)
  --help, -h         Show this help
`;

type Status = 'PASS' | 'FORMAT' | 'FAIL' | 'SKIPPED' | 'ERROR';

interface CellResult {
  repo: string;
  type: string;
  strategy: string;
  format: string;
  nestedPerms: boolean;
  status: Status;
  decomposed: number;
  skippedFiles: { path: string; reason: string }[];
}

interface ResultsFile {
  results: CellResult[];
}

/** Every results.json under `dir`, at any depth. */
function findResultsFiles(dir: string): string[] {
  const found: string[] = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) found.push(...findResultsFiles(path));
    else if (name === 'results.json') found.push(path);
  }
  return found;
}

/** `windows` / `ubuntu` / `macos` from a CI artifact path (`corpus-<repo>-windows-latest/...`). */
function platformOf(path: string): string | undefined {
  return /(ubuntu|windows|macos)-latest/.exec(path)?.[1];
}

const isVerified = (r: CellResult): boolean => (r.status === 'PASS' || r.status === 'FORMAT') && r.decomposed > 0;

const plural = (n: number, word: string): string => `${n} ${word}${n === 1 ? '' : 's'}`;

function repoLink(name: string, repos: Map<string, CorpusRepo>): string {
  const repo = repos.get(name);
  return repo ? `[${name}](${repo.url})` : name;
}

export function buildCoveragePage(
  results: CellResult[],
  corpus: CorpusRepo[],
  meta: { platforms: string[]; source?: string; generated: string },
): string {
  const repos = new Map(corpus.map((r) => [r.name, r]));
  const failed = results.filter((r) => r.status === 'FAIL' || r.status === 'ERROR');
  const failedTypes = new Set(failed.map((r) => `${r.repo}\u0000${r.type}`));

  // type -> repo -> { components (max decomposed in any cell), whitespace-only? }
  const verified = new Map<string, Map<string, { components: number; whitespaceOnly: boolean }>>();
  const skipped = new Map<string, { repos: Set<string>; reasons: Set<string> }>();
  for (const r of results) {
    if (isVerified(r) && !failedTypes.has(`${r.repo}\u0000${r.type}`)) {
      const byRepo = verified.get(r.type) ?? new Map();
      const prev = byRepo.get(r.repo) ?? { components: 0, whitespaceOnly: false };
      byRepo.set(r.repo, {
        components: Math.max(prev.components, r.decomposed),
        whitespaceOnly: prev.whitespaceOnly || r.status === 'FORMAT',
      });
      verified.set(r.type, byRepo);
    } else if (r.status === 'SKIPPED') {
      const entry = skipped.get(r.type) ?? { repos: new Set(), reasons: new Set() };
      entry.repos.add(r.repo);
      for (const f of r.skippedFiles) entry.reasons.add(f.reason);
      skipped.set(r.type, entry);
    }
  }
  for (const type of verified.keys()) skipped.delete(type);

  const strategies = [...new Set(results.map((r) => r.strategy))].sort();
  const formats = [...new Set(results.map((r) => r.format))].sort();
  const withNestedPerms = results.some((r) => r.nestedPerms);
  const projects = [...new Set(results.map((r) => r.repo))].sort((a, b) => a.localeCompare(b));
  const byName = (a: string, b: string): number => a.localeCompare(b, 'en', { sensitivity: 'base' });
  const totalComponents = [...verified.values()].reduce(
    (sum, byRepo) => sum + [...byRepo.values()].reduce((s, v) => s + v.components, 0),
    0,
  );

  const lines: string[] = [
    '# Corpus coverage',
    '',
    '<!-- Generated by `npm run corpus:coverage`; do not edit by hand. -->',
    '',
    'Metadata types the [corpus harness](README.md) decomposed and recomposed in real public Salesforce DX',
    'projects, each cloned at a pinned commit. A type is listed as verified for a project when every file',
    'came back byte-for-byte after `decompose --postpurge` and `recompose --postpurge`, or differed only',
    'in whitespace, as in files formatted with tools like Prettier.',
    '',
    `- **Run:** ${meta.source ?? 'local'}, generated ${meta.generated}`,
    `- **Platforms:** ${meta.platforms.join(', ') || 'unknown'}`,
    `- **Strategies:** ${strategies.join(', ')}${withNestedPerms ? ', plus `--decompose-nested-permissions` for permission sets' : ''}`,
    `- **Formats:** ${formats.join(', ')}`,
    `- **Totals:** ${plural(projects.length, 'project')}, ${plural(verified.size, 'metadata type')} verified, ${plural(totalComponents, 'component')} round-tripped`,
    '',
  ];

  if (failed.length) {
    lines.push(
      '## Failures',
      '',
      'Not counted as verified above.',
      '',
      '| Project | Type | Strategy | Format | Status |',
    );
    lines.push('| --- | --- | --- | --- | --- |');
    for (const r of failed) {
      lines.push(
        `| ${repoLink(r.repo, repos)} | \`${r.type}\` | ${r.strategy}${r.nestedPerms ? ' -p' : ''} | ${r.format} | ${r.status} |`,
      );
    }
    lines.push('');
  }

  lines.push(
    '## Verified metadata types',
    '',
    'Components: the most files decomposed in one run, summed across projects. _Whitespace only_ marks',
    'projects where some files differed only in whitespace.',
    '',
    '| Metadata type | Projects | Components |',
    '| --- | --- | ---: |',
  );
  for (const type of [...verified.keys()].sort(byName)) {
    const byRepo = verified.get(type) as Map<string, { components: number; whitespaceOnly: boolean }>;
    const names = [...byRepo.keys()].sort(byName);
    const projectsCell = names
      .map((name) => `${name}${byRepo.get(name)?.whitespaceOnly ? ' _(whitespace only)_' : ''}`)
      .join(', ');
    const components = [...byRepo.values()].reduce((s, v) => s + v.components, 0);
    lines.push(`| \`${type}\` | ${projectsCell} | ${components} |`);
  }
  lines.push('');

  if (skipped.size) {
    lines.push(
      '## Found but not decomposed',
      '',
      'These types appear in the corpus, but none of their files had anything to decompose (for example',
      'only leaf elements). sf-decomposer leaves such files unchanged, and the corpus confirms they are',
      'untouched, but their decomposition is not exercised here.',
      '',
      '| Metadata type | Projects | Reason |',
      '| --- | --- | --- |',
    );
    for (const type of [...skipped.keys()].sort(byName)) {
      const entry = skipped.get(type) as { repos: Set<string>; reasons: Set<string> };
      const reasons = [...entry.reasons].sort().join('; ') || 'nothing decomposed';
      lines.push(`| \`${type}\` | ${[...entry.repos].sort(byName).join(', ')} | ${reasons} |`);
    }
    lines.push('');
  }

  lines.push('## Projects', '', '| Project | Commit | Types verified |', '| --- | --- | ---: |');
  for (const name of projects) {
    const repo = repos.get(name);
    const commit = repo ? `[\`${repo.sha.slice(0, 7)}\`](${repo.url}/tree/${repo.sha})` : '';
    const count = [...verified.values()].filter((byRepo) => byRepo.has(name)).length;
    lines.push(`| ${repoLink(name, repos)} | ${commit} | ${count} |`);
  }
  lines.push('');
  return lines.join('\n');
}

function main(argv: readonly string[]): void {
  if (argv.includes('--help') || argv.includes('-h')) {
    process.stdout.write(HELP_TEXT);
    return;
  }
  const flags = parseFlags(argv);
  const reportsDir = resolve(requireString(flags, 'reports', 'See --help.'));
  const outPath = resolve((flags.get('out') as string | undefined) ?? join(HERE, 'COVERAGE.md'));
  const corpusPath = resolve((flags.get('corpus') as string | undefined) ?? join(HERE, 'corpus.json'));
  const source = flags.get('source') as string | undefined;

  const files = findResultsFiles(reportsDir);
  if (files.length === 0) throw new Error(`No results.json found under ${reportsDir}`);
  const results: CellResult[] = [];
  const platforms = new Set<string>();
  for (const file of files) {
    const parsed = JSON.parse(readFileSync(file, 'utf8')) as ResultsFile;
    results.push(...parsed.results);
    const platform = platformOf(file);
    if (platform) platforms.add(platform);
  }
  const corpus = JSON.parse(readFileSync(corpusPath, 'utf8')) as CorpusRepo[];

  const page = buildCoveragePage(results, corpus, {
    platforms: [...platforms].sort(),
    source,
    generated: new Date().toISOString().slice(0, 10),
  });
  writeFileSync(outPath, page);
  process.stdout.write(`Wrote ${outPath} from ${files.length} results file(s).\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
